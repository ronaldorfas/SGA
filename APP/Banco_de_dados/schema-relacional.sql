create or replace function preparar_datas_manutencao()
returns trigger
language plpgsql
as $$
begin
  if new.status is distinct from old.status then
    if new.status = 'Aprovada' then
      new.aprovado_em = coalesce(new.aprovado_em, now());
    elsif new.status = 'Em atendimento' then
      new.atendimento_inicio = coalesce(new.atendimento_inicio, now());
    elsif new.status = 'Finalizada' then
      new.finalizada_em = coalesce(new.finalizada_em, now());
    end if;
  end if;
  return new;
end;
$$;

create or replace function registrar_evento_manutencao()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    insert into historico_manutencao (sugestao_id, status_novo, observacao, acao, criadoem)
    values (new.id, new.status, new.comentario, 'Sugestão recebida', new.criadoem);
    return new;
  end if;

  if new.status is distinct from old.status then
    insert into historico_manutencao (
      sugestao_id, status_anterior, status_novo, responsavel_id, observacao, acao
    )
    values (
      new.id, old.status, new.status, new.responsavel_id, new.comentario,
      'Status alterado de ' || old.status || ' para ' || new.status
    );

    if new.status = 'Aprovada' then
      insert into ocorrencias_manutencao (
        sugestao_id, ambiente_id, solicitante, descricao, tipo_ocorrencia,
        prioridade, responsavel_id, status, criadoem, aprovado_em
      )
      values (
        new.id, new.ambiente_id, new.nome, new.sujestao, new.tipo_ocorrencia,
        new.prioridade, new.responsavel_id, new.status, new.criadoem, new.aprovado_em
      );
    elsif new.status in ('Em atendimento', 'Finalizada') then
      update ocorrencias_manutencao
      set status = new.status,
          responsavel_id = new.responsavel_id,
          atendimento_inicio = new.atendimento_inicio,
          finalizada_em = new.finalizada_em
      where sugestao_id = new.id;
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_sugestoes_manutencao_historico on sugestoes_manutencao;
create trigger trg_sugestoes_manutencao_historico
after insert or update of status on sugestoes_manutencao
for each row execute function registrar_evento_manutencao();
drop trigger if exists trg_sugestoes_manutencao_datas on sugestoes_manutencao;
create trigger trg_sugestoes_manutencao_datas
before update of status on sugestoes_manutencao
for each row execute function preparar_datas_manutencao();

insert into historico_manutencao (sugestao_id, status_novo, acao, criadoem)
select s.id, s.status, 'Registro migrado; histórico anterior indisponível', s.criadoem
from sugestoes_manutencao s
where not exists (
  select 1 from historico_manutencao h where h.sugestao_id = s.id
);

