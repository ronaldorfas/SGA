create table if not exists alocacoes_ambiente (
  id bigint generated by default as identity primary key,
  atribuicao_aula_id bigint not null,
  ambiente_id bigint not null,
  dia_semana text,
  periodo text,
  horario text
);

alter table alocacoes_ambiente add column if not exists dia_semana text;
alter table alocacoes_ambiente add column if not exists periodo text;
alter table alocacoes_ambiente add column if not exists horario text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'alocacoes_ambiente_dia_semana_check'
      and conrelid = 'public.alocacoes_ambiente'::regclass
  ) then
    alter table alocacoes_ambiente
      add constraint alocacoes_ambiente_dia_semana_check
      check (dia_semana is null or dia_semana in (
        'Segunda-feira', 'Terça-feira', 'Quarta-feira',
        'Quinta-feira', 'Sexta-feira', 'Sábado'
      )) not valid;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'ambientes_capacidade_check'
      and conrelid = 'public.ambientes'::regclass
  ) then
    alter table ambientes
      add constraint ambientes_capacidade_check
      check (capacidade is null or capacidade > 0) not valid;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'alocacoes_ambiente_horario_check'
      and conrelid = 'public.alocacoes_ambiente'::regclass
  ) then
    alter table alocacoes_ambiente
      add constraint alocacoes_ambiente_horario_check
      check (
        dia_semana is not null
        and periodo is not null
        and horario is not null
        and dia_semana in (
          'Segunda-feira', 'Terça-feira', 'Quarta-feira',
          'Quinta-feira', 'Sexta-feira', 'Sábado'
        )
        and (
          (periodo = 'Manhã' and horario in ('07:00 - 08:50', '09:10 - 11:00'))
          or (periodo = 'Tarde' and horario in ('12:00 - 13:50', '14:10 - 16:00'))
          or (periodo = 'Noite' and horario in ('18:30 - 20:10', '20:20 - 22:00'))
          or (periodo = 'Integral' and horario in (
            '07:00 - 08:50', '09:10 - 11:00',
            '12:00 - 13:50', '14:10 - 16:00'
          ))
        )
      ) not valid;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'alocacoes_ambiente_periodo_check'
      and conrelid = 'public.alocacoes_ambiente'::regclass
  ) then
    alter table alocacoes_ambiente
      add constraint alocacoes_ambiente_periodo_check
      check (periodo is null or periodo in ('Manhã', 'Tarde', 'Noite', 'Integral')) not valid;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'alocacoes_ambiente_atribuicao_fk'
      and conrelid = 'public.alocacoes_ambiente'::regclass
  ) then
    alter table alocacoes_ambiente
      add constraint alocacoes_ambiente_atribuicao_fk
      foreign key (atribuicao_aula_id) references turma_componentes_docentes(id) on delete cascade not valid;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'alocacoes_ambiente_ambiente_fk'
      and conrelid = 'public.alocacoes_ambiente'::regclass
  ) then
    alter table alocacoes_ambiente
      add constraint alocacoes_ambiente_ambiente_fk
      foreign key (ambiente_id) references ambientes(id) not valid;
  end if;
end $$;

create index if not exists idx_alocacoes_ambiente_atribuicao
  on alocacoes_ambiente(atribuicao_aula_id);
create index if not exists idx_alocacoes_ambiente_ambiente_dia
  on alocacoes_ambiente(ambiente_id, dia_semana);
create unique index if not exists uq_alocacoes_ambiente_horario
  on alocacoes_ambiente(ambiente_id, dia_semana, horario)
  where dia_semana is not null and horario is not null;

