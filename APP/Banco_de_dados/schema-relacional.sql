insert into ocorrencias_manutencao (
  sugestao_id, ambiente_id, solicitante, descricao, tipo_ocorrencia,
  prioridade, responsavel_id, status, criadoem, aprovado_em,
  atendimento_inicio, finalizada_em
)
select
  s.id, s.ambiente_id, s.nome, s.sujestao,
  coalesce(s.tipo_ocorrencia, 'Não classificada'),
  coalesce(s.prioridade, 'Não classificada'),
  s.responsavel_id, s.status, s.criadoem, s.aprovado_em,
  s.atendimento_inicio, s.finalizada_em
from sugestoes_manutencao s
where s.status in ('Aprovada', 'Em atendimento', 'Finalizada')
  and exists (select 1 from ambientes a where a.id = s.ambiente_id)
  and not exists (
    select 1 from ocorrencias_manutencao o where o.sugestao_id = s.id
  );

