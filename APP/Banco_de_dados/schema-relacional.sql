update sugestoes_manutencao
set status = case
  when lower(btrim(status)) = 'pendente' then 'Pendente de análise'
  when lower(btrim(status)) in ('concluída', 'concluida') then 'Finalizada'
  when status in ('Pendente de análise', 'Em análise', 'Não aprovada', 'Aprovada', 'Em atendimento', 'Finalizada') then status
  else 'Pendente de análise'
end;
update sugestoes_manutencao
set criadoem = now()
where criadoem is null;

